//! Shell snippet generation from the Lua config.
//!
//! Idea: the user writes config in Lua, Zuchu compiles it into a bash/zsh
//! hook file that is sourced by shell sessions (colors, prompt, env).
//! Bash here is a build *artifact*, not a config language.

use std::io::Write;
use std::path::PathBuf;

use crate::config::Config;

/// Hook path: ~/.config/zuchu/shell/zuchu-hook.sh
pub fn hook_path(_cfg: &Config) -> PathBuf {
    crate::config::config_dir().join("shell").join("zuchu-hook.sh")
    // (_cfg is in the signature — later hooks may depend on profile/theme tag)
}

/// Generates and writes the hook file; returns its path.
pub fn write_hook(cfg: &Config) -> Result<PathBuf, Box<dyn std::error::Error>> {
    let path = hook_path(cfg);
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }

    // Convert 0..1 floats to 0..255 integers once, reuse below
    let (r, g, b) = (rgb8(cfg.theme.fg.0), rgb8(cfg.theme.fg.1), rgb8(cfg.theme.fg.2));
    let content = format!(
        r#"# Auto-generated by Zuchu v0.1 — DO NOT EDIT BY HAND.
# Source of truth: config.lua (regenerated on every zuchu start)

# --- colors from theme ---
export ZUCHU_FG="{r};{g};{b}"

# --- prompt tinted with the Zuchu theme color ---
if [ -n "$ZSH_VERSION" ]; then
  ZUCHU_PROMPT_COLOR=$'\e[38;2;{r};{g};{b}m'
  # First stage: a minimal prompt (an OMZ theme will override this var —
  # that is fine; a dedicated Zuchu prompt engine lands in v0.2).
elif [ -n "$BASH_VERSION" ]; then
  PS1='\[\e[38;2;{r};{g};{b}m\]\w\[\e[0m\] \[\e[32m\]$\[\e[0m\] '
fi

# --- helper for opening directories from within Zuchu ---
zuchu-open() {{
  # v0.2 will open this in a new Zuchu tab/window via IPC; for now — plain cd
  if [ -d "$1" ]; then cd "$1" || return 1; else cd "$OLDPWD" || return 1; fi
}}
"#
    );

    let mut f = std::fs::File::create(&path)?;
    f.write_all(content.as_bytes())?;
    Ok(path)
}

fn rgb8(v: f32) -> u8 {
    (clamp01(v) * 255.0).round() as u8
}

fn clamp01(v: f32) -> f32 {
    v.clamp(0.0, 1.0)
}
